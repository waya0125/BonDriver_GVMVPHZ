bool WriteTuner(saa7164::Client *c, uint8_t reg, uint8_t val) {
    return c->I2CWrite(kTunerUnit, reg, {val, 0xfe});
}

bool WriteDemod(saa7164::Client *c, uint8_t reg, uint8_t val) {
    return c->I2CWrite(kDemodUnit, reg, {val});
}

void SleepMs(int ms) {
    std::this_thread::sleep_for(std::chrono::milliseconds(ms));
}

bool LookupFreq(uint32_t freq_hz, FreqEntry *out) {
    if (freq_hz < 90000000u || freq_hz > 773000000u) return false;
    for (const auto &e : kFreqTable) {
        if (freq_hz < e.freq_hz + 3000000u) {
            *out = e;
            return true;
        }
    }
    *out = kFreqTable[sizeof(kFreqTable) / sizeof(kFreqTable[0]) - 1];
    return true;
}

