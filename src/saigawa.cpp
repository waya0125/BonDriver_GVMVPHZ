bool Init(saa7164::Client *c) {
    if (!c->SetGPIO(kDemodUnit, 0, 0)) return false;
    SleepMs(10);
    if (!c->SetGPIO(kDemodUnit, 0, 1)) return false;
    SleepMs(2000);

    c->I2CWrite(kTunerUnit, 0xff, {0xff});
    if (!WriteTuner(c, 0x09, 0xb1)) return false;
    SleepMs(1);
    for (const auto &rv : kTunerInitRegs) {
        if (!WriteTuner(c, rv.reg, rv.val)) return false;
    }
    for (const auto &rv : kDemodInitRegs) {
        if (!WriteDemod(c, rv.reg, rv.val)) return false;
    }
    return true;
}

bool TuneISDBT(saa7164::Client *c, uint32_t freq_hz, bool *locked_out) {
    if (locked_out) *locked_out = false;
    FreqEntry ent{};
    if (!LookupFreq(freq_hz, &ent)) return false;

    constexpr RegVal kHeader[] = {
        {0xa8, 0xd2}, {0x95, 0x03}, {0x09, 0xb1}, {0x88, 0x7e}, {0x8a, 0x38},
    };
    for (const auto &rv : kHeader) {
        if (!WriteTuner(c, rv.reg, rv.val)) return false;
    }
    for (size_t i = 0; i < kFreqRegAddrs.size(); ++i) {
        if (!WriteTuner(c, kFreqRegAddrs[i], ent.regs[i])) return false;
    }
    if (!WriteTuner(c, 0x09, 0xf3)) return false;
    SleepMs(30);
    if (!WriteTuner(c, 0x88, 0xfe)) return false;
    if (!WriteTuner(c, 0x09, 0xf3)) return false;
    if (!WriteDemod(c, 0x01, 0x40)) return false;

    for (int i = 0; i < 20; ++i) {
        SleepMs(150);
        uint8_t r80 = 0, rb0 = 0;
        bool locked = false;
        if (ReadLock(c, &r80, &rb0, &locked) && locked) {
            if (locked_out) *locked_out = true;
            return true;
        }
    }
    return true;
}

bool ReadLock(saa7164::Client *c, uint8_t *r80, uint8_t *rb0, bool *locked) {
    std::vector<uint8_t> v1, v2;
    if (!c->I2CRead(kDemodUnit, 0x80, 1, &v1) || v1.empty()) return false;
    if (!c->I2CRead(kDemodUnit, 0xb0, 1, &v2) || v2.empty()) return false;
    if (r80) *r80 = v1[0];
    if (rb0) *rb0 = v2[0];
    if (locked) *locked = ((v1[0] & 0x28) == 0) && ((v2[0] & 0x0f) >= 8);
    return true;
}

bool ReadSignalStrength(saa7164::Client *c, uint8_t *strength_out) {
    std::vector<uint8_t> v;
    if (!c->I2CRead(kDemodUnit, 0x94, 1, &v) || v.empty()) return false;
    if (strength_out) *strength_out = v[0];
    return true;
}

